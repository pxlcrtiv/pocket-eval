"""Report rendering: stable markdown and JSON views of an EvalReport."""

from __future__ import annotations

import json

from .core import EvalReport


def render_markdown(r: EvalReport) -> str:
    """Deterministic markdown report (no timestamps)."""
    lines = [
        "# pocket-eval report",
        "",
        f"- model: **{r.model}**",
        f"- backend: `{r.backend}`" + (f" (seed {r.seed})" if r.seed is not None else ""),
        "",
        "## Perplexity (bundled corpus)",
        "",
    ]
    if r.corpus_ppl is not None:
        lines += [
            "| metric | value |",
            "| --- | --- |",
            f"| corpus tokens | {r.corpus_tokens} |",
            f"| corpus perplexity | {r.corpus_ppl:.2f} |",
        ]
    else:
        lines.append("_not evaluated_")
    lines += [
        "",
        "## Multiple-choice QA (bundled mini-benchmark)",
        "",
        "| metric | value |",
        "| --- | --- |",
        f"| questions | {r.qa_total} |",
        f"| correct | {r.qa_correct} |",
        f"| accuracy | {r.qa_accuracy:.1%} |",
    ]
    if r.qa_details:
        lines += ["", "### Per-question"]
        for d in r.qa_details:
            mark = "correct" if d.correct else "missed  "
            lines.append(
                f"- `{d.item_id}` {mark} — picked option {d.predicted} "
                f"(score {d.score:.4f})"
            )
    if r.notes:
        lines += ["", "## Notes", ""] + [f"- {n}" for n in r.notes]
    lines += ["", "_Generated by `pocket-eval`; deterministic given model + seed._"]
    return "\n".join(lines)


def render_json(r: EvalReport) -> str:
    """Stable JSON rendering (sorted keys, no timestamps)."""
    payload = {
        "model": r.model,
        "backend": r.backend,
        "seed": r.seed,
        "corpus": {
            "tokens": r.corpus_tokens,
            "perplexity": r.corpus_ppl,
        },
        "qa": {
            "total": r.qa_total,
            "correct": r.qa_correct,
            "accuracy": r.qa_accuracy,
            "details": [
                {"id": d.item_id, "predicted": d.predicted, "correct": d.correct, "score": d.score}
                for d in r.qa_details
            ],
        },
        "notes": r.notes,
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"